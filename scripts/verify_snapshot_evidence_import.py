"""Synthetic isolated-schema PostgreSQL rehearsal; all DDL and rows roll back."""
import copy
import json
import os
import sqlite3
from contextlib import closing

import psycopg
from psycopg import sql
from psycopg.rows import dict_row
from ibkr_etl.snapshot_evidence import COLUMNS, TABLE, inspect_financial_evidence
from ibkr_etl.snapshot_evidence_import import bundle_fingerprint, import_financial_evidence
from ibkr_etl.snapshot_atomic_import import TABLE_KEYS, combined_fingerprint, stage_combined_snapshot
from ibkr_etl.pilot_snapshot import ACCOUNT_TABLES
from ibkr_etl.util import canonical_json, sha256_text

SCHEMA = "ibkr_snapshot_evidence_trial"
ROLE = "ibkr_snapshot_evidence_trial_role"
ACCOUNT = "synthetic-evidence-trial"
OTHER_TENANT = "00000000-0000-0000-0000-000000000002"


def fixture():
    rows = []
    source_run = dict(run_id=901, run_type="synthetic", requested_from="2025-01-20",
                      requested_to="2025-01-20", status="success", started_at="2025-01-21",
                      completed_at="2025-01-21", raw_sha256="a" * 64)
    lineage = canonical_json({role: {"source_run_id": 901, "run": source_run}
                              for role in ("first_seen", "last_seen")})
    for key, section, kind in [("1", "Transfers", "Transfer"), ("2", "ConversionRates", "ConversionRate")]:
        raw = canonical_json({"accountId": ACCOUNT, "reportDate": "20250120", "amount": "100"})
        rows.append(dict(account_id=ACCOUNT, section=section, record_type=kind, source_key=key,
                         report_date="2025-01-20", conid=None, currency="USD", row_sha256=sha256_text(raw),
                         data_json=raw, source_lineage_json=lineage))
    with closing(sqlite3.connect(":memory:")) as c:
        c.execute(f"CREATE TABLE {TABLE} ({','.join(k + ' TEXT' for k in COLUMNS)})")
        c.executemany(f"INSERT INTO {TABLE} VALUES ({','.join('?' for _ in COLUMNS)})",
                      [[row[k] for k in COLUMNS] for row in rows])
        summary = inspect_financial_evidence(c, account_id=ACCOUNT, start_date="2025-01-20", source_table_available=True)
    bundle = dict(account_id=ACCOUNT, start_date="2025-01-20", snapshot_sha256="b" * 64, summary=summary, rows=rows)
    bundle["bundle_sha256"] = bundle_fingerprint(bundle)
    return bundle


def main():
    tenant = os.environ["PORTFOLIO_TENANT_ID"]
    bundle = fixture()
    checks = []
    def check(name, condition):
        if not condition:
            raise ValueError("Rehearsal failed: " + name)
        checks.append(name)
    with psycopg.connect(os.environ["DATABASE_URL"], autocommit=True, row_factory=dict_row,
                         connect_timeout=25, options="-c statement_timeout=60000 -c lock_timeout=5000") as c:
        def absent():
            return (not c.execute("SELECT 1 FROM pg_namespace WHERE nspname=%s", (SCHEMA,)).fetchone()
                    and not c.execute("SELECT 1 FROM pg_roles WHERE rolname=%s", (ROLE,)).fetchone())
        check("no_preexisting_trial_objects", absent())
        with c.transaction(force_rollback=True):
            c.execute(sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(SCHEMA)))
            for table in ("accounts", "ingestion_runs", "flex_rows", *TABLE_KEYS):
                c.execute(sql.SQL("CREATE TABLE {} (LIKE {} INCLUDING CONSTRAINTS INCLUDING INDEXES)")
                          .format(sql.Identifier(SCHEMA, table), sql.Identifier("public", table)))
            c.execute(sql.SQL("ALTER TABLE {} ALTER COLUMN flex_row_id ADD GENERATED BY DEFAULT AS IDENTITY")
                      .format(sql.Identifier(SCHEMA, "flex_rows")))
            for column in ("first_seen_run_id", "last_seen_run_id"):
                c.execute(sql.SQL("ALTER TABLE {} ADD FOREIGN KEY ({}) REFERENCES {}(run_id)")
                          .format(sql.Identifier(SCHEMA, "flex_rows"), sql.Identifier(column),
                                  sql.Identifier(SCHEMA, "ingestion_runs")))
            c.execute(sql.SQL("INSERT INTO {} (account_id,base_currency,first_seen_at,last_seen_at,source_json,tenant_id) VALUES (%s,'USD','trial','trial','{{}}',%s)")
                      .format(sql.Identifier(SCHEMA, "accounts")), (ACCOUNT, tenant))
            for run_id in (7001, 7002, 7004, 7005, 7006, 7007, 7008):
                c.execute(sql.SQL("INSERT INTO {} (run_id,run_type,requested_from,started_at,status,raw_sha256,tenant_id) VALUES (%s,'staging-snapshot-import','2025-01-20','trial',%s,%s,%s)")
                          .format(sql.Identifier(SCHEMA, "ingestion_runs")),
                          (run_id, "success" if run_id == 7002 else "running", bundle["snapshot_sha256"],
                           OTHER_TENANT if run_id == 7004 else tenant))
            c.execute(sql.SQL("CREATE ROLE {} NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS").format(sql.Identifier(ROLE)))
            c.execute(sql.SQL("GRANT {} TO CURRENT_USER").format(sql.Identifier(ROLE)))
            c.execute(sql.SQL("GRANT USAGE ON SCHEMA {} TO {}").format(sql.Identifier(SCHEMA), sql.Identifier(ROLE)))
            c.execute(sql.SQL("GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA {} TO {}").format(sql.Identifier(SCHEMA), sql.Identifier(ROLE)))
            c.execute(sql.SQL("GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA {} TO {}").format(sql.Identifier(SCHEMA), sql.Identifier(ROLE)))
            for table in ("accounts", "ingestion_runs", "flex_rows", *ACCOUNT_TABLES):
                identifier = sql.Identifier(SCHEMA, table)
                c.execute(sql.SQL("ALTER TABLE {} ENABLE ROW LEVEL SECURITY").format(identifier))
                c.execute(sql.SQL("ALTER TABLE {} FORCE ROW LEVEL SECURITY").format(identifier))
                columns = {r["column_name"] for r in c.execute("SELECT column_name FROM information_schema.columns WHERE table_schema=%s AND table_name=%s", (SCHEMA, table))}
                if "tenant_id" in columns:
                    policy = sql.SQL("tenant_id::text=current_setting('app.tenant_id',true)")
                else:
                    policy = sql.SQL("EXISTS (SELECT 1 FROM {} a WHERE a.account_id={}.account_id AND a.tenant_id::text=current_setting('app.tenant_id',true))").format(sql.Identifier(SCHEMA, "accounts"), sql.Identifier(table))
                c.execute(sql.SQL("CREATE POLICY scoped_evidence ON {} USING ({}) WITH CHECK ({})").format(identifier, policy, policy))
            c.execute(sql.SQL("SET LOCAL ROLE {}").format(sql.Identifier(ROLE)))
            c.execute("SELECT set_config('app.tenant_id',%s,true)", (tenant,))
            def apply(value=bundle, run=7001, scope=tenant):
                return import_financial_evidence(c, value, tenant_id=scope, run_id=run, schema=SCHEMA)
            def rejected(name, call):
                try:
                    with c.transaction():
                        call()
                except ValueError:
                    checks.append(name)
                else:
                    raise ValueError("Expected rejection missing: " + name)
            first = apply()
            check("inserted_and_read_back_exact_values", first["inserted_rows"] == first["verified_rows"] == 2)
            table = sql.Identifier(SCHEMA, "flex_rows")
            runs = sql.Identifier(SCHEMA, "ingestion_runs")
            observed = c.execute(sql.SQL("SELECT first_seen_run_id,last_seen_run_id FROM {}").format(table)).fetchall()
            check("source_run_ids_remapped", all(r["first_seen_run_id"] == r["last_seen_run_id"] == 7001 for r in observed))
            record = c.execute(sql.SQL("SELECT status,reconciliation_json FROM {} WHERE run_id=7001").format(runs)).fetchone()
            receipt = json.loads(record["reconciliation_json"])["financial_evidence_import"]
            check("source_provenance_retained", receipt["mappings"][0]["source_lineage"]["first_seen"]["source_run_id"] == 901)
            check("no_run_success_or_workflow_authority", record["status"] == "running" and not receipt["reconciliation_authorized"])
            check("idempotent_same_run", apply()["inserted_rows"] == 0)
            rejected("wrong_session_tenant_blocked", lambda: apply(scope=OTHER_TENANT))
            rejected("foreign_tenant_run_blocked", lambda: apply(run=7004))
            altered = copy.deepcopy(bundle)
            altered["snapshot_sha256"] = "c" * 64
            altered["bundle_sha256"] = bundle_fingerprint(altered)
            rejected("wrong_snapshot_digest_blocked", lambda: apply(altered, run=7005))
            c.execute("SELECT set_config('app.tenant_id',%s,true)", (OTHER_TENANT,))
            check("rls_hides_other_account_evidence", not c.execute(sql.SQL("SELECT 1 FROM {}").format(table)).fetchone())
            rejected("wrong_account_owner_blocked", lambda: apply(scope=OTHER_TENANT, run=7004))
            c.execute("SELECT set_config('app.tenant_id',%s,true)", (tenant,))
            altered = copy.deepcopy(bundle)
            altered["rows"][0]["source_key"] = "new-before-conflict"
            attrs = json.loads(altered["rows"][1]["data_json"])
            attrs["amount"] = "999"
            altered["rows"][1]["data_json"] = canonical_json(attrs)
            altered["rows"][1]["row_sha256"] = sha256_text(canonical_json(attrs))
            altered["bundle_sha256"] = bundle_fingerprint(altered)
            rejected("conflicting_values_not_overwritten", lambda: apply(altered, run=7005))
            check("partial_insert_rolled_back", not c.execute(sql.SQL("SELECT 1 FROM {} WHERE source_key='new-before-conflict'").format(table)).fetchone())
            check("failed_attempt_has_no_receipt", c.execute(sql.SQL("SELECT reconciliation_json FROM {} WHERE run_id=7005").format(runs)).fetchone()["reconciliation_json"] is None)
            check("original_values_retained", apply()["verified_rows"] == 2)
            # Same content in a later run reuses, but does not rewrite, old lineage.
            c.execute(sql.SQL("UPDATE {} SET first_seen_run_id=7002,last_seen_run_id=7002").format(table))
            check("existing_rows_reused", apply(run=7006)["inserted_rows"] == 0)
            check("existing_destination_lineage_retained", all(r["first_seen_run_id"] == r["last_seen_run_id"] == 7002
                  for r in c.execute(sql.SQL("SELECT first_seen_run_id,last_seen_run_id FROM {}").format(table))))
            rejected("receipt_detects_later_lineage_change", apply)
            empty = copy.deepcopy(bundle)
            empty["rows"] = []
            empty["summary"].update(preserved_rows=0, category_counts={"Transfers": 0, "FX": 0})
            empty["bundle_sha256"] = bundle_fingerprint(empty)
            check("empty_evidence_does_not_certify_completeness", apply(empty, run=7007)["source_completeness"] == "unverified")
            combined_trial(c, bundle, tenant, check, rejected)
        check("schema_role_and_fixture_data_rolled_back", absent())
    print("SNAPSHOT_EVIDENCE_TRIAL " + json.dumps({"status": "PASS", "mode": "isolated_schema_rollback_only",
                                                 "checks": checks, "check_count": len(checks),
                                                 "production_financial_rows_written": 0, "source_completeness": "unverified"}))


def combined_trial(c, evidence, tenant, check, rejected):
    # Build synthetic rows with the actual destination column shapes. No public
    # data are copied; normalized values are fixed test strings.
    tables = {}
    for table in TABLE_KEYS:
        info = c.execute("SELECT column_name,is_nullable FROM information_schema.columns WHERE table_schema=%s AND table_name=%s ORDER BY ordinal_position", (SCHEMA, table)).fetchall()
        row = {r["column_name"]: ("trial" if r["is_nullable"] == "NO" else None) for r in info
               if r["column_name"] not in {"tenant_id", "last_seen_run_id"}}
        values = dict(account_id=ACCOUNT, conid="synthetic-conid", source_key="combined-trial", model_code="",
                      currency="USD", from_currency="USD", to_currency="HKD", asset_class="TOTAL",
                      first_seen_at="2025-01-20", last_seen_at="2025-01-20", row_sha256="e" * 64,
                      total_text="100", rate_text="1", market_value_text="100", source_json="{}")
        row.update({k: v for k, v in values.items() if k in row})
        if table in ACCOUNT_TABLES:
            row[ACCOUNT_TABLES[table][0]] = "2025-01-20"
        tables[table] = {"columns": list(row), "rows": [row]}
    source = copy.deepcopy(evidence)
    new_row = dict(source["rows"][0], source_key="combined-new")
    source["rows"].append(new_row)
    source["summary"]["preserved_rows"] += 1
    source["summary"]["category_counts"]["Transfers"] += 1
    source["bundle_sha256"] = bundle_fingerprint(source)
    combined = dict(evidence=source, account_base_currency="USD", tables=tables)
    combined["combined_sha256"] = combined_fingerprint(combined)
    def stage(value=combined):
        return stage_combined_snapshot(c, value, tenant_id=tenant, run_id=7008, schema=SCHEMA)
    def insert_row(table, row):
        values = dict(row, last_seen_run_id=7002)
        c.execute(sql.SQL("INSERT INTO {} ({}) VALUES ({})").format(
            sql.Identifier(SCHEMA, table), sql.SQL(",").join(map(sql.Identifier, values)),
            sql.SQL(",").join(sql.Placeholder() for _ in values)), list(values.values()))
    nav = sql.Identifier(SCHEMA, "nav_snapshots")
    flex = sql.Identifier(SCHEMA, "flex_rows")
    runs = sql.Identifier(SCHEMA, "ingestion_runs")
    # Late failure after evidence, instruments and multiple normalized tables.
    insert_row("nav_snapshots", dict(tables["nav_snapshots"]["rows"][0], total_text="999"))
    rejected("combined_late_value_conflict_rejected", stage)
    check("combined_evidence_insert_rolled_back", not c.execute(sql.SQL("SELECT 1 FROM {} WHERE source_key='combined-new'").format(flex)).fetchone())
    check("combined_instruments_rolled_back", not c.execute(sql.SQL("SELECT 1 FROM {}").format(sql.Identifier(SCHEMA, "instruments"))).fetchone())
    check("combined_earlier_financial_rows_rolled_back", not c.execute(sql.SQL("SELECT 1 FROM {}").format(sql.Identifier(SCHEMA, "trades"))).fetchone())
    check("combined_receipts_rolled_back", c.execute(sql.SQL("SELECT reconciliation_json FROM {} WHERE run_id=7008").format(runs)).fetchone()["reconciliation_json"] is None)
    check("conflicting_nav_retained", c.execute(sql.SQL("SELECT total_text FROM {}").format(nav)).fetchone()["total_text"] == "999")
    # Restore only synthetic fixture data and keep an out-of-scope historical row.
    c.execute(sql.SQL("UPDATE {} SET total_text='100'").format(nav))
    insert_row("nav_snapshots", dict(tables["nav_snapshots"]["rows"][0], snapshot_date="2024-12-31"))
    good = stage()
    check("combined_all_nine_tables_verified", len(good["verified_tables"]) == 9 and all(x["verified_rows"] == 1 for x in good["verified_tables"].values()))
    check("combined_evidence_and_financial_rows_present", good["evidence"]["verified_rows"] == 3 and good["inserted_rows"]["trades"] == 1)
    check("out_of_scope_history_retained", c.execute(sql.SQL("SELECT count(*) AS n FROM {}").format(nav)).fetchone()["n"] == 2)
    again = stage()
    check("combined_repeat_is_idempotent", sum(again["inserted_rows"].values()) == 0 and again["evidence"]["inserted_rows"] == 0)
    check("combined_does_not_mark_run_success", c.execute(sql.SQL("SELECT status FROM {} WHERE run_id=7008").format(runs)).fetchone()["status"] == "running")
    currency = copy.deepcopy(combined)
    currency["account_base_currency"] = "HKD"
    currency["combined_sha256"] = combined_fingerprint(currency)
    rejected("account_currency_mismatch_blocked", lambda: stage(currency))
    fx = sql.Identifier(SCHEMA, "fx_rates")
    c.execute(sql.SQL("UPDATE {} SET rate_text='0'").format(fx))
    rejected("same_count_value_corruption_detected", stage)
    c.execute(sql.SQL("UPDATE {} SET rate_text='1'").format(fx))
    check("readback_recovers_after_fixture_restoration", stage()["verified_tables"]["fx_rates"]["verified_rows"] == 1)
    c.execute(sql.SQL("DELETE FROM {}").format(fx))
    rejected("missing_previously_staged_row_not_silently_reinserted", stage)
    check("missing_row_remains_for_review", not c.execute(sql.SQL("SELECT 1 FROM {}").format(fx)).fetchone())


if __name__ == "__main__":
    main()
